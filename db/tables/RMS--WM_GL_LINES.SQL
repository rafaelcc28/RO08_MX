CREATE OR REPLACE TRIGGER WMUSER.WM_GL_LINES_BI_TRG
BEFORE INSERT
ON WMUSER.WM_GL_LINES REFERENCING NEW AS NEW OLD AS OLD
FOR EACH ROW
DECLARE
tmpVar NUMBER;


BEGIN
   tmpVar := 0;

   SELECT WM_GL_LINES_S.NEXTVAL INTO tmpVar FROM DUAL;
   :NEW.LINE_ID := tmpVar;

   EXCEPTION
     WHEN OTHERS THEN
       -- Consider logging the error and then re-raise
       RAISE;
END ;
/


